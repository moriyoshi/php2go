// Command surfacegen classifies the public functions owned by php-src/main
// and php-src/ext/standard against php2go's native and userland dispatchers.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var functionDeclaration = regexp.MustCompile("(?m)^function[[:space:]]+([A-Za-z_][A-Za-z0-9_]*)[[:space:]]*\\(")

// linkedUnavailable is the build-conditional part of the stub-declared scope
// that the linked engine does not register. surface_test.go asks that engine
// about every ledger name, so this profile cannot silently drift from reality.
var linkedUnavailable = map[string]bool{
	"chroot":                           true,
	"config_get_hash":                  true,
	"fnmatch":                          true,
	"proc_close":                       true,
	"proc_get_status":                  true,
	"proc_open":                        true,
	"proc_terminate":                   true,
	"sapi_windows_cp_conv":             true,
	"sapi_windows_cp_get":              true,
	"sapi_windows_cp_is_utf8":          true,
	"sapi_windows_cp_set":              true,
	"sapi_windows_generate_ctrl_event": true,
	"sapi_windows_set_ctrl_handler":    true,
	"sapi_windows_vt100_support":       true,
	"sys_getloadavg":                   true,
}

func main() {
	root := flag.String("root", ".", "repository root")
	output := flag.String("output", "internal/userland/surface.tsv", "output path")
	check := flag.Bool("check", false, "fail if the output is stale")
	flag.Parse()

	out, err := generateSurface(*root)
	if err != nil {
		fail(err)
	}
	outputPath := *output
	if !filepath.IsAbs(outputPath) {
		outputPath = filepath.Join(*root, outputPath)
	}
	if *check {
		current, err := os.ReadFile(outputPath)
		if err != nil {
			fail(err)
		}
		if !bytes.Equal(current, out) {
			fail(fmt.Errorf("%s is stale; run go generate ./internal/userland", outputPath))
		}
		return
	}
	if err := os.WriteFile(outputPath, out, 0o644); err != nil {
		fail(err)
	}
}

func generateSurface(root string) ([]byte, error) {
	scope, err := publicFunctions(root)
	if err != nil {
		return nil, err
	}
	native, err := nativeFunctions(filepath.Join(root, "runtime", "interp"))
	if err != nil {
		return nil, err
	}
	// Two packages register into the shared table: `runtime/php` still holds a
	// handful alongside the value semantics, and `runtime/stdlib` is where the
	// library surface both back-ends link now lives.
	for _, dir := range []struct{ path, pkg string }{
		{filepath.Join(root, "runtime", "php"), "php"},
		{filepath.Join(root, "runtime", "stdlib"), "stdlib"},
	} {
		sharedNative, err := registeredFunctions(dir.path, dir.pkg)
		if err != nil {
			return nil, err
		}
		for name := range sharedNative {
			native[name] = true
		}
	}
	userland, err := userlandFunctions(filepath.Join(root, "internal", "userland", "catalog.go"))
	if err != nil {
		return nil, err
	}

	var out bytes.Buffer
	fmt.Fprintln(&out, "# Generated by go generate ./internal/userland; DO NOT EDIT.")
	fmt.Fprintln(&out, "# Public global functions declared by php-src/main and php-src/ext/standard.")
	fmt.Fprintln(&out, "# name\tdisposition")
	for _, name := range sortedKeys(scope) {
		disposition := "pending"
		if linkedUnavailable[name] {
			disposition = "unavailable"
		}
		if native[name] {
			if linkedUnavailable[name] {
				return nil, fmt.Errorf("%s is both native and unavailable", name)
			}
			disposition = "native"
		}
		if userland[name] {
			if native[name] || linkedUnavailable[name] {
				return nil, fmt.Errorf("%s has conflicting userland disposition", name)
			}
			disposition = "userland"
		}
		fmt.Fprintf(&out, "%s\t%s\n", name, disposition)
	}
	for name := range userland {
		if !scope[name] {
			return nil, fmt.Errorf("userland function %s is outside the main/ext-standard scope", name)
		}
	}
	for name := range linkedUnavailable {
		if !scope[name] {
			return nil, fmt.Errorf("unavailable function %s is outside the main/ext-standard scope", name)
		}
	}
	return out.Bytes(), nil
}

func publicFunctions(root string) (map[string]bool, error) {
	functions := map[string]bool{}
	for _, base := range []string{
		filepath.Join(root, "third_party", "php-src", "main"),
		filepath.Join(root, "third_party", "php-src", "ext", "standard"),
	} {
		err := filepath.WalkDir(base, func(path string, entry os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".stub.php") {
				return nil
			}
			contents, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			for _, match := range functionDeclaration.FindAllSubmatch(contents, -1) {
				functions[strings.ToLower(string(match[1]))] = true
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	return functions, nil
}

func nativeFunctions(dir string) (map[string]bool, error) {
	fset := token.NewFileSet()
	packages, err := parser.ParseDir(fset, dir, func(info os.FileInfo) bool {
		return strings.HasSuffix(info.Name(), ".go") && !strings.HasSuffix(info.Name(), "_test.go")
	}, 0)
	if err != nil {
		return nil, err
	}
	pkg := packages["interp"]
	if pkg == nil {
		return nil, fmt.Errorf("package interp not found in %s", dir)
	}
	names := map[string]bool{}
	for _, file := range pkg.Files {
		ast.Inspect(file, func(node ast.Node) bool {
			switch node := node.(type) {
			case *ast.AssignStmt:
				for _, lhs := range node.Lhs {
					if name, ok := builtinIndex(lhs); ok {
						names[name] = true
					}
				}
			case *ast.ValueSpec:
				for index, ident := range node.Names {
					if ident.Name != "builtins" && ident.Name != "arrayBuiltins" {
						continue
					}
					if index < len(node.Values) {
						collectStringKeys(node.Values[index], names)
					}
				}
			case *ast.RangeStmt:
				key, ok := node.Key.(*ast.Ident)
				if !ok || !assignsBuiltin(node.Body, key.Name) {
					break
				}
				collectStringKeys(node.X, names)
			}
			return true
		})
		for _, declaration := range file.Decls {
			fn, ok := declaration.(*ast.FuncDecl)
			if !ok || fn.Body == nil || !strings.HasSuffix(fn.Name.Name, "Builtin") || !hasStringParameter(fn, "name") {
				continue
			}
			ast.Inspect(fn.Body, func(node ast.Node) bool {
				switchStmt, ok := node.(*ast.SwitchStmt)
				if !ok {
					return true
				}
				ident, ok := switchStmt.Tag.(*ast.Ident)
				if !ok || ident.Name != "name" {
					return true
				}
				for _, statement := range switchStmt.Body.List {
					clause := statement.(*ast.CaseClause)
					for _, expression := range clause.List {
						if name, ok := stringLiteral(expression); ok {
							names[name] = true
						}
					}
				}
				return true
			})
		}
	}
	return names, nil
}

// registeredFunctions finds runtime/php's shared builtin registrations. These
// still enter the interpreter through its dispatch bridge, but their bodies no
// longer appear in the interpreter package's native maps.
func registeredFunctions(dir, pkgName string) (map[string]bool, error) {
	fset := token.NewFileSet()
	packages, err := parser.ParseDir(fset, dir, func(info os.FileInfo) bool {
		return strings.HasSuffix(info.Name(), ".go") &&
			!strings.HasSuffix(info.Name(), "_test.go")
	}, 0)
	if err != nil {
		return nil, err
	}
	pkg := packages[pkgName]
	if pkg == nil {
		return nil, fmt.Errorf("package %s not found in %s", pkgName, dir)
	}
	names := map[string]bool{}
	for _, file := range pkg.Files {
		ast.Inspect(file, func(node ast.Node) bool {
			// A whole table can be registered by ranging over a map literal --
			// the trig functions are -- and then the name argument is the loop
			// variable rather than a literal. The keys of the ranged map are
			// the names, exactly as `nativeFunctions` already reads them on the
			// interpreter's side.
			if loop, ok := node.(*ast.RangeStmt); ok {
				key, ok := loop.Key.(*ast.Ident)
				if ok && registersBuiltin(loop.Body, key.Name) {
					collectStringKeys(loop.X, names)
				}
				return true
			}
			call, ok := node.(*ast.CallExpr)
			if !ok || len(call.Args) == 0 {
				return true
			}
			if !isRegisterBuiltin(call.Fun) {
				return true
			}
			if name, ok := stringLiteral(call.Args[0]); ok {
				names[name] = true
			}
			return true
		})
	}
	return names, nil
}

func builtinIndex(expression ast.Expr) (string, bool) {
	index, ok := expression.(*ast.IndexExpr)
	if !ok {
		return "", false
	}
	ident, ok := index.X.(*ast.Ident)
	if !ok || ident.Name != "builtins" {
		return "", false
	}
	return stringLiteral(index.Index)
}

func collectStringKeys(expression ast.Expr, names map[string]bool) {
	literal, ok := expression.(*ast.CompositeLit)
	if !ok {
		return
	}
	for _, element := range literal.Elts {
		pair, ok := element.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		if name, ok := stringLiteral(pair.Key); ok {
			names[name] = true
		}
	}
}

// isRegisterBuiltin matches both spellings of the call: bare inside
// `runtime/php`, and qualified as `php.RegisterBuiltin` from `runtime/stdlib`.
// Matching only the bare one silently read the stdlib package as registering
// nothing, and reported its whole surface as `pending`.
func isRegisterBuiltin(fun ast.Expr) bool {
	switch fn := fun.(type) {
	case *ast.Ident:
		return fn.Name == "RegisterBuiltin"
	case *ast.SelectorExpr:
		pkg, ok := fn.X.(*ast.Ident)
		return ok && pkg.Name == "php" && fn.Sel.Name == "RegisterBuiltin"
	}
	return false
}

// registersBuiltin reports whether body calls RegisterBuiltin with the named
// loop variable as the function name -- the `RegisterBuiltin` twin of
// assignsBuiltin.
func registersBuiltin(body *ast.BlockStmt, key string) bool {
	found := false
	ast.Inspect(body, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok || len(call.Args) == 0 {
			return true
		}
		if !isRegisterBuiltin(call.Fun) {
			return true
		}
		if arg, ok := call.Args[0].(*ast.Ident); ok && arg.Name == key {
			found = true
		}
		return true
	})
	return found
}

func assignsBuiltin(body *ast.BlockStmt, key string) bool {
	found := false
	ast.Inspect(body, func(node ast.Node) bool {
		assignment, ok := node.(*ast.AssignStmt)
		if !ok {
			return true
		}
		for _, lhs := range assignment.Lhs {
			index, ok := lhs.(*ast.IndexExpr)
			if !ok {
				continue
			}
			ident, ok := index.X.(*ast.Ident)
			keyIdent, keyOK := index.Index.(*ast.Ident)
			if ok && keyOK && ident.Name == "builtins" && keyIdent.Name == key {
				found = true
			}
		}
		return true
	})
	return found
}

func hasStringParameter(fn *ast.FuncDecl, wanted string) bool {
	for _, field := range fn.Type.Params.List {
		ident, ok := field.Type.(*ast.Ident)
		if !ok || ident.Name != "string" {
			continue
		}
		for _, name := range field.Names {
			if name.Name == wanted {
				return true
			}
		}
	}
	return false
}

func userlandFunctions(path string) (map[string]bool, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return nil, err
	}
	names := map[string]bool{}
	ast.Inspect(file, func(node ast.Node) bool {
		pair, ok := node.(*ast.KeyValueExpr)
		if !ok {
			return true
		}
		ident, ok := pair.Key.(*ast.Ident)
		if !ok || ident.Name != "Name" {
			return true
		}
		if name, ok := stringLiteral(pair.Value); ok {
			names[name] = true
		}
		return true
	})
	return names, nil
}

func stringLiteral(expression ast.Expr) (string, bool) {
	literal, ok := expression.(*ast.BasicLit)
	if !ok || literal.Kind != token.STRING {
		return "", false
	}
	value, err := strconv.Unquote(literal.Value)
	if err != nil {
		return "", false
	}
	return strings.ToLower(value), true
}

func sortedKeys(values map[string]bool) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "surfacegen:", err)
	os.Exit(1)
}
