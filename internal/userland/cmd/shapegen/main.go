// Command shapegen measures the shape of the `PHP2Go\Internal\*` layer -- the
// helpers a userland PHP body calls when it needs something PHP cannot do.
//
// It exists because a conversion can be complete and still be wrong. The
// streams library is the case that prompted it: every function has a PHP body,
// and the bodies call one helper per *area* with a string naming the operation
// --
//
//	\PHP2Go\Internal\stream_operation($stream, 'flush')
//	\PHP2Go\Internal\stream_context('merge_options', $context, $options)
//
// which is `php_stream_set_option(stream, option, value, ptrparam)` carried
// across unchanged. In C the selector is a constant passed to one entry point.
// In PHP it should be separate functions with real signatures, and the
// difference is not taste: a multiplexed helper has no signature to type, its
// Go side is an arm of a switch rather than a function, and every caller pays
// for the union of what any caller needs.
//
// Two numbers per helper, both mechanical:
//
//   - **selectors**: the largest number of distinct string literals appearing in
//     any single argument position across its call sites. 0 means the helper
//     takes data. 2 or more means it takes an *opcode*, and is a multiplexer.
//   - **reachable**: whether compiled code can call it at all. A helper that
//     lives only in the interpreter's dispatcher makes every userland function
//     that uses it impossible to emit, however good its PHP is.
//
// The output is a table, checked in and regenerated by `go generate`, so a
// conversion that adds a multiplexer or an unreachable helper arrives as a diff
// in review rather than as an opinion afterwards.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/moriyoshi/php2go/internal/userland"
	"github.com/moriyoshi/php2go/runtime/php"
	_ "github.com/moriyoshi/php2go/runtime/stdlib"
)

type helper struct {
	name      string
	calls     int
	selectors int
}

var callSite = regexp.MustCompile(`\\PHP2Go\\Internal\\([A-Za-z_][A-Za-z0-9_]*)\s*\(`)

func main() {
	root := flag.String("root", ".", "repository root")
	output := flag.String("output", "", "path to write, relative to root")
	flag.Parse()

	table, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "shapegen:", err)
		os.Exit(1)
	}
	if *output == "" {
		os.Stdout.Write(table)
		return
	}
	if err := os.WriteFile(filepath.Join(*root, *output), table, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "shapegen:", err)
		os.Exit(1)
	}
}

func generate() ([]byte, error) {
	helpers := map[string]*helper{}
	// Every argument position's distinct string literals, per helper.
	literals := map[string]map[int]map[string]bool{}

	for _, library := range userland.Libraries() {
		source := string(library.Source)
		for _, match := range callSite.FindAllStringSubmatchIndex(source, -1) {
			name := source[match[2]:match[3]]
			entry := helpers[name]
			if entry == nil {
				entry = &helper{name: name}
				helpers[name] = entry
				literals[name] = map[int]map[string]bool{}
			}
			entry.calls++
			for position, argument := range arguments(source, match[1]-1) {
				text, ok := stringLiteral(argument)
				if !ok {
					continue
				}
				if literals[name][position] == nil {
					literals[name][position] = map[string]bool{}
				}
				literals[name][position][text] = true
			}
		}
	}

	names := make([]string, 0, len(helpers))
	for name := range helpers {
		names = append(names, name)
		for _, seen := range literals[name] {
			if len(seen) > helpers[name].selectors {
				helpers[name].selectors = len(seen)
			}
		}
	}
	sort.Strings(names)

	reachable := map[string]bool{}
	for _, name := range php.BuiltinNames() {
		reachable[strings.ToLower(name)] = true
	}

	var out bytes.Buffer
	multiplexers, unreachable := 0, 0
	for _, name := range names {
		if helpers[name].selectors > 1 {
			multiplexers++
		}
		if !reachable[`php2go\internal\`+strings.ToLower(name)] {
			unreachable++
		}
	}
	fmt.Fprintln(&out, "# Generated by go generate ./internal/userland; DO NOT EDIT.")
	fmt.Fprintln(&out, "# The PHP2Go\\Internal\\* helpers a userland PHP body calls.")
	fmt.Fprintln(&out, "#")
	fmt.Fprintln(&out, "# selectors: distinct string literals in one argument position. 2 or more")
	fmt.Fprintln(&out, "#   means the helper takes an operation name rather than data -- a C-shaped")
	fmt.Fprintln(&out, "#   multiplexer, which has no signature to type and no function on the Go side.")
	fmt.Fprintln(&out, "# reachable: whether compiled code can call it. An unreachable helper makes")
	fmt.Fprintln(&out, "#   every userland function that uses it impossible to emit.")
	fmt.Fprintf(&out, "# totals: %d helpers, %d multiplexers, %d unreachable from compiled code\n",
		len(names), multiplexers, unreachable)
	fmt.Fprintln(&out, "# helper\tcalls\tselectors\treachable")
	for _, name := range names {
		mark := "no"
		if reachable[`php2go\internal\`+strings.ToLower(name)] {
			mark = "yes"
		}
		fmt.Fprintf(&out, "%s\t%d\t%d\t%s\n", name, helpers[name].calls, helpers[name].selectors, mark)
	}
	return out.Bytes(), nil
}

// arguments splits the argument list that starts at the given open parenthesis,
// at top-level commas. Nested calls, arrays and strings are skipped over rather
// than parsed -- the only thing wanted here is which arguments are literals.
func arguments(source string, open int) []string {
	depth := 0
	start := open + 1
	var out []string
	for index := open; index < len(source); index++ {
		switch character := source[index]; character {
		case '\'', '"':
			index = skipString(source, index)
		case '(', '[':
			depth++
		case ')', ']':
			depth--
			if depth == 0 {
				out = append(out, source[start:index])
				return out
			}
		case ',':
			if depth == 1 {
				out = append(out, source[start:index])
				start = index + 1
			}
		}
	}
	return out
}

func skipString(source string, start int) int {
	quote := source[start]
	for index := start + 1; index < len(source); index++ {
		if source[index] == '\\' {
			index++
			continue
		}
		if source[index] == quote {
			return index
		}
	}
	return len(source) - 1
}

// selectorLike distinguishes an **operation name** from data. A selector is an
// identifier -- `merge_options`, `isatty` -- and a message is a sentence. Without
// this the diagnostic helpers dominate the table: `\PHP2Go\Internal\warning`
// takes 39 distinct string literals across 83 calls and multiplexes nothing,
// because every one of them is the warning's text.
var selectorLike = regexp.MustCompile(`^[a-z][a-z0-9_-]*$`)

func stringLiteral(argument string) (string, bool) {
	trimmed := strings.TrimSpace(argument)
	if len(trimmed) < 2 {
		return "", false
	}
	quote := trimmed[0]
	if quote != '\'' && quote != '"' {
		return "", false
	}
	if trimmed[len(trimmed)-1] != quote {
		return "", false
	}
	text := trimmed[1 : len(trimmed)-1]
	if len(text) > 32 || !selectorLike.MatchString(text) {
		return "", false
	}
	return text, true
}
